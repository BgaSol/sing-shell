import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync, spawnSync} from 'node:child_process';

assert.equal(process.env.SING_SHELL_NETWORK_PREFLIGHT, '1');
assert.equal(process.platform, 'darwin');
const directory = path.resolve('artifacts/network-preflight/aarch64-apple-darwin');
fs.mkdirSync(directory, {recursive: true});
const bundle = '/Applications/Sing Shell Network Preflight.app';
assert.equal(fs.existsSync(bundle), false, 'refuse to overwrite an existing application');
const contents = path.join(bundle, 'Contents');
fs.mkdirSync(path.join(contents, 'MacOS'), {recursive: true});
fs.mkdirSync(path.join(contents, 'Library/LaunchDaemons'), {recursive: true});
fs.mkdirSync(path.join(contents, 'Library/HelperTools'), {recursive: true});
const executable = path.join(contents, 'MacOS/network-service-probe');
const helper = path.join(contents, 'Library/HelperTools/network-service-worker');
const marker = path.join(directory, 'service-worker.json');
const plist = value => `<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0">${value}</plist>`;
fs.writeFileSync(path.join(contents, 'Info.plist'), plist('<dict><key>CFBundleIdentifier</key><string>com.bgasol.singshell.preflight</string><key>CFBundleExecutable</key><string>network-service-probe</string><key>CFBundleName</key><string>Sing Shell Network Preflight</string><key>CFBundlePackageType</key><string>APPL</string><key>CFBundleVersion</key><string>1</string></dict>'));
fs.writeFileSync(path.join(contents, 'Library/LaunchDaemons/com.bgasol.singshell.preflight.plist'), plist(`<dict><key>Label</key><string>com.bgasol.singshell.preflight</string><key>UserName</key><string>root</string><key>AssociatedBundleIdentifiers</key><array><string>com.bgasol.singshell.preflight</string></array><key>BundleProgram</key><string>Contents/Library/HelperTools/network-service-worker</string><key>ProgramArguments</key><array><string>network-service-worker</string><string>--helper</string><string>${marker}</string></array><key>RunAtLoad</key><true/></dict>`));
execFileSync('swiftc', ['scripts/macos-service-preflight.swift', '-o', executable]);
fs.copyFileSync(executable, helper);
execFileSync('codesign', ['--force', '--sign', '-', '--options', 'runtime', '--identifier', 'com.bgasol.singshell.preflight.worker', helper]);
execFileSync('codesign', ['--force', '--sign', '-', '--options', 'runtime', '--identifier', 'com.bgasol.singshell.preflight', bundle]);
const result = spawnSync(executable, [marker], {encoding: 'utf8', timeout: 30_000});
fs.writeFileSync(path.join(directory, 'service-report.json'), result.stdout || JSON.stringify({error: String(result.error), stderr: result.stderr}));
console.log(result.stdout);
if (result.stderr) console.error(result.stderr);
const serviceReport = JSON.parse(result.stdout || '{}');
if (serviceReport.manualApprovalRequired) {
  console.log('SMAppService registered a pending approval: interactive approval and launchd activation remain unverified.');
}
execFileSync('sudo', ['-n', helper, '--helper', marker]);
const worker = JSON.parse(fs.readFileSync(marker, 'utf8'));
assert.equal(worker.effectiveUid, 0);
assert.equal(worker.helperRan, true);
fs.writeFileSync(path.join(directory, 'service-worker-report.json'), JSON.stringify({passed: true, directElevatedWorker: worker, skipped: serviceReport.manualApprovalRequired ? ['interactive authorization and launchd activation after user approval'] : []}, null, 2));
const signing = spawnSync('codesign', ['--display', '--verbose=4', bundle], {encoding: 'utf8'});
console.log(signing.stderr);
const diagnostics = spawnSync('/usr/bin/log', ['show', '--last', '2m', '--style', 'compact', '--predicate', 'process == "smd" OR process == "backgroundtaskmanagementd"'], {encoding: 'utf8', timeout: 20_000});
fs.writeFileSync(path.join(directory, 'service-diagnostics.log'), diagnostics.stdout ?? '');
console.log((diagnostics.stdout ?? '').split('\n').filter(line => /sign|deny|error|permitted|preflight|bundle/i.test(line)).slice(-60).join('\n'));
assert.equal(result.status, 0, 'SMAppService must enable the service or expose a real requiresApproval state');
